// Writes firmware/Fulcrum/spec.h from core/spec.js so the robot and the simulator share every constant.
import fs from 'node:fs';
import * as S from '../core/spec.js';

const FLOATS = new Set(['OBS_CLIP', 'PID_KP', 'PID_KI', 'PID_KD', 'THETA_MAX_DEG', 'DEFAULT_US_PER_DEG', 'LEVEL_KP', 'LEVEL_KD', 'LEVEL_KT', 'LEVEL_MAX_DEG', 'BALLTEST_DEG']);
const f = (v, name) => {
  if (Number.isInteger(v) && !FLOATS.has(name)) return String(v);
  if (Number.isInteger(v)) return `${v}.0f`;
  const s = v.toPrecision(9).replace(/0+$/, '').replace(/\.$/, '.0');
  return s.includes('e') || s.includes('.') ? `${s}f` : `${s}.0f`;
};
const lines = [
  '// GENERATED by tools/gen_spec.mjs from core/spec.js. Do not edit; edit spec.js and regenerate.',
  '#pragma once',
  '',
  `#define FW_VERSION "${S.FIRMWARE_VERSION}"`,
];
const skip = new Set(['MODE', 'MODE_NAMES', 'PIN', 'IR', 'IR_NAMES', 'FIRMWARE_VERSION']);
for (const [k, v] of Object.entries(S)) {
  if (skip.has(k) || typeof v !== 'number') continue;
  lines.push(`#define ${k} ${f(v, k)}`);
}
lines.push('', `#define DT_US ${Math.round(S.DT * 1e6)}UL`, '');
for (const [k, v] of Object.entries(S.MODE)) lines.push(`#define MODE_${k} ${v}`);
lines.push('');
for (const [k, v] of Object.entries(S.PIN)) lines.push(`#define PIN_${k} ${v}`);
lines.push('');
for (const [k, v] of Object.entries(S.IR)) lines.push(`#define IR_${k} 0x${v.toString(16).toUpperCase().padStart(2, '0')}`);
lines.push('');
const out = new URL('../firmware/Fulcrum/spec.h', import.meta.url);
fs.writeFileSync(out, lines.join('\n'));
console.log('wrote', out.pathname);
